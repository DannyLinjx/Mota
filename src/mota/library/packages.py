"""Immutable component-library packages in the MoTA 12 contract shape.

One package is one asset at one package version. `manifest.json` is the package
entry point: it lists every persistent file (path, role, sha256) and the
package digest is the SHA-256 of the manifest bytes. Nothing here reads the
design or the catalog index; this module writes and validates packages on disk.

`asset_id` is the identity. Directory names are only storage names generated by
`package_relpath`; they can never be used to infer an identity.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import unicodedata
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Mapping

from mota.library import contract

SCHEMA_VERSION = 1
KINDS = contract.KINDS
PLURAL = contract.PLURAL
CAPABILITIES = contract.CAPABILITIES
FILE_ROLES = contract.FILE_ROLES
DOC_STATUSES = ("stub", "basic", "partial", "verified")
PACKAGE_MODES = ("metadata_only", "asset")

DEFAULT_ROLES = {
    "README.md": "readme",
    "usage.md": "usage",
    "parameters.json": "parameters",
    "pins.json": "pins",
    "bindings.json": "bindings",
    "rules.json": "rules",
    "provenance.json": "provenance",
    "license.txt": "license",
    "preview.png": "preview",
    "geometry.json": "other",
    "pads.json": "other",
    "symbol.kicad_sym": "symbol_geometry",
    "footprint.kicad_mod": "footprint_geometry",
}

_RESERVED = {"con", "prn", "aux", "nul", "com1", "com2", "com3", "com4",
             "lpt1", "lpt2", "lpt3"}


def utcnow() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def canonical_json(payload: Any) -> bytes:
    return json.dumps(payload, ensure_ascii=False, sort_keys=True,
                      separators=(",", ":")).encode("utf-8")


def json_bytes(payload: Any) -> bytes:
    return json.dumps(payload, ensure_ascii=False, indent=1,
                      sort_keys=True).encode("utf-8")


def text_bytes(text: str) -> bytes:
    return text.encode("utf-8")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def stable_id(namespace: str, kind: str, key: str) -> str:
    if kind not in KINDS:
        raise ValueError(f"unknown asset kind {kind!r}")
    if not namespace or ":" in namespace or "/" in namespace:
        raise ValueError(f"invalid namespace {namespace!r}")
    if not key:
        raise ValueError("asset key is required")
    return f"{namespace}:{kind}:{key}"


def parse_stable_id(asset_id: str) -> tuple[str, str, str]:
    parts = str(asset_id).split(":", 2)
    if len(parts) != 3 or parts[1] not in KINDS or not parts[2]:
        raise ValueError(f"not a stable asset id: {asset_id}")
    return parts[0], parts[1], parts[2]


def slugify(text: str, limit: int = 64) -> str:
    value = unicodedata.normalize("NFKD", text).casefold()
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    value = value or "asset"
    if value in _RESERVED:
        value = f"{value}-asset"
    return value[:limit].strip("-")


def dir_name(display_name: str, asset_id: str) -> str:
    """Readable slug plus identity hash; identical names cannot collide."""
    return f"{slugify(display_name)}--{sha256_bytes(asset_id.encode())[:10]}"


def namespace_dir(namespace: str) -> str:
    if re.fullmatch(r"[a-z0-9][a-z0-9._-]*", namespace):
        return namespace
    return slugify(namespace)


def package_relpath(kind: str, namespace: str, display_name: str,
                    asset_id: str) -> str:
    return f"{PLURAL[kind]}/{namespace_dir(namespace)}/{dir_name(display_name, asset_id)}"


def package_dir(root: Path, entry: dict[str, Any]) -> Path:
    return root / entry["relative_path"] / "versions" / entry["package_version"]


def safe_relpath(relative: str) -> str:
    try:
        return contract.safe_relpath(relative)
    except contract.ContractError as exc:
        raise ValueError(str(exc)) from exc


@dataclass
class PackageWrite:
    asset_id: str
    kind: str
    display_name: str
    package_version: str
    summary: str
    payload: dict[str, bytes]
    namespace: str = "mota"
    category: str = "uncategorized"
    tags: list[str] = field(default_factory=list)
    origin: dict[str, str] | None = None
    legacy_ids: list[str] = field(default_factory=list)
    dependencies: list[dict[str, str]] = field(default_factory=list)
    documentation_level: str = "basic"
    missing_fields: list[str] = field(default_factory=list)
    package_mode: str = "asset"
    capabilities: set[str] | None = None
    license: dict[str, Any] | None = None
    sources: list[dict[str, Any]] = field(default_factory=list)
    file_roles: dict[str, str] = field(default_factory=dict)


def _payload_json(payload: Mapping[str, bytes], name: str) -> Any:
    data = payload.get(name)
    if data is None:
        return None
    try:
        return json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        return None


def _pin_count(payload: Mapping[str, bytes]) -> int:
    geometry = _payload_json(payload, "geometry.json") or {}
    if geometry.get("pins"):
        return len(geometry["pins"])
    pins = _payload_json(payload, "pins.json") or {}
    return len(pins.get("symbol_occurrences") or [])


def _pad_count(payload: Mapping[str, bytes]) -> int:
    pads = _payload_json(payload, "pads.json") or {}
    return len(pads.get("pads") or [])


def capabilities_for(write: PackageWrite) -> dict[str, bool]:
    """Capabilities are derived from what the package actually contains.

    A `metadata_only` package can never advertise placement; the schema
    enforces that, and the derivation here keeps placement tied to real files
    instead of a hopeful string.
    """
    caps = {name: False for name in CAPABILITIES}
    metadata_only = write.package_mode == "metadata_only"
    caps["metadata_only"] = metadata_only
    roles = {_role_for(name, write.file_roles) for name in write.payload}
    caps["documentation_read"] = bool(roles & {"usage", "readme"})
    if metadata_only:
        return caps

    pins = _pin_count(write.payload)
    pads = _pad_count(write.payload)
    has_bindings = "bindings.json" in write.payload
    has_parameters = "parameters.json" in write.payload
    has_geometry = bool(roles & {"symbol_geometry", "footprint_geometry",
                                 "model3d_geometry", "module_definition",
                                 "template_definition"})

    if write.kind == "component":
        caps["parameter_read"] = has_parameters
        caps["schematic_place"] = has_bindings and pins > 0
        caps["pcb_place"] = has_bindings and pads > 0
    elif write.kind == "symbol":
        caps["parameter_read"] = has_parameters
        caps["schematic_place"] = pins > 0
    elif write.kind == "footprint":
        caps["pcb_place"] = pads > 0
    elif write.kind == "model3d":
        caps["model3d_view"] = has_geometry
    elif write.kind == "module":
        caps["module_expand"] = "module_definition" in roles
    elif write.kind == "template":
        caps["template_instantiate"] = "template_definition" in roles

    if write.capabilities is not None:
        for name in write.capabilities:
            if name in caps:
                caps[name] = True
    return caps


def _role_for(path: str, overrides: Mapping[str, str] | None = None) -> str:
    if overrides and path in overrides:
        role = overrides[path]
    else:
        role = DEFAULT_ROLES.get(path, "other")
    if role not in FILE_ROLES:
        raise ValueError(f"unknown file role {role!r} for {path!r}")
    return role


def build_manifest(write: PackageWrite) -> tuple[dict[str, Any], bytes]:
    files: list[dict[str, str]] = []
    for name, data in sorted(write.payload.items()):
        rel = safe_relpath(name)
        files.append({"path": rel, "role": _role_for(rel, write.file_roles),
                      "sha256": sha256_bytes(data)})
    caps = capabilities_for(write)
    license_block = write.license or {"expression": None, "status": "unknown"}
    if license_block.get("status") == "known" and not license_block.get("expression"):
        raise ValueError("a known license needs an expression")
    if license_block.get("status") == "unknown":
        license_block = {"expression": None, "status": "unknown"}
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "asset_id": write.asset_id,
        "kind": write.kind,
        "namespace": write.namespace,
        "display_name": write.display_name,
        "summary": write.summary or write.display_name,
        "category": write.category,
        "tags": sorted(set(write.tags)),
        "package_version": write.package_version,
        "package_mode": write.package_mode,
        "origin": write.origin or {"provider_id": write.namespace,
                                   "source_id": write.namespace,
                                   "source_version": "1"},
        "legacy_ids": sorted(set(write.legacy_ids)),
        "documentation": {"level": write.documentation_level,
                          "missing_fields": sorted(set(write.missing_fields))},
        "license": license_block,
        "sources": list(write.sources),
        "files": files,
        "dependencies": sorted(
            (dict(dep) for dep in write.dependencies),
            key=lambda dep: (dep.get("asset_id", ""), dep.get("version", ""))),
    }
    raw = json_bytes(manifest)
    contract.validate_manifest(manifest)
    return manifest, raw


def entry_from_manifest(manifest: Mapping[str, Any], digest: str,
                        pkg_dir: Path, root: Path, *,
                        enabled: bool = True,
                        availability: str = "available") -> dict[str, Any]:
    relative = pkg_dir.parent.parent.relative_to(root).as_posix()
    return {
        "asset_id": manifest["asset_id"],
        "kind": manifest["kind"],
        "namespace": manifest["namespace"],
        "display_name": manifest["display_name"],
        "summary": manifest["summary"],
        "package_version": manifest["package_version"],
        "digest": digest,
        "relative_path": relative,
        "enabled": enabled,
        "availability": availability,
        "documentation_status": manifest["documentation"]["level"],
        "capabilities": capabilities_from_manifest(manifest),
    }


def capabilities_from_manifest(manifest: Mapping[str, Any]) -> dict[str, bool]:
    """Reconstruct the capability object from the manifest's real files."""
    mode = manifest.get("package_mode", "metadata_only")
    files = manifest.get("files") or []
    roles = {row["role"] for row in files}
    names = {row["path"].rsplit("/", 1)[-1] for row in files}
    caps = {name: False for name in CAPABILITIES}
    caps["metadata_only"] = mode == "metadata_only"
    caps["documentation_read"] = bool(roles & {"readme", "usage"})
    if mode == "metadata_only":
        return caps
    kind = manifest.get("kind")
    has_pins = "pins.json" in names
    has_pads = "pads.json" in names
    has_bindings = "bindings.json" in names
    if kind == "component":
        caps["parameter_read"] = "parameters" in roles
        caps["schematic_place"] = has_bindings and has_pins
        caps["pcb_place"] = has_bindings and has_pads
    elif kind == "symbol":
        caps["parameter_read"] = "parameters" in roles
        caps["schematic_place"] = has_pins
    elif kind == "footprint":
        caps["pcb_place"] = has_pads
    elif kind == "model3d":
        caps["model3d_view"] = "model3d_geometry" in roles
    elif kind == "module":
        caps["module_expand"] = "module_definition" in roles
    elif kind == "template":
        caps["template_instantiate"] = "template_definition" in roles
    return caps


def write_package(root: Path, write: PackageWrite) -> dict[str, Any]:
    """Write one immutable package version and return its index entry.

    Writing is staged next to the final directory and renamed atomically, so an
    interrupted write never leaves a half package that looks installable.
    """
    relative = package_relpath(write.kind, write.namespace,
                               write.display_name, write.asset_id)
    final = root / relative / "versions" / write.package_version
    manifest, raw = build_manifest(write)
    digest = sha256_bytes(raw)
    if final.exists():
        existing = final / "manifest.json"
        if existing.exists() and existing.read_bytes() == raw:
            contract.validate_manifest(manifest, pkg_dir=final)
            return entry_from_manifest(manifest, digest, final, root)
        raise PackageConflict(
            f"{write.asset_id} {write.package_version} already exists with a "
            f"different digest")
    final.parent.mkdir(parents=True, exist_ok=True)
    staging = final.parent / f".staging-{os.getpid()}-{os.urandom(4).hex()}"
    staging.mkdir()
    try:
        for name, data in write.payload.items():
            target = staging / safe_relpath(name)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        (staging / "manifest.json").write_bytes(raw)
        contract.validate_manifest(manifest, pkg_dir=staging)
        if final.exists():
            raise PackageConflict(f"{write.asset_id} appeared while installing")
        os.replace(staging, final)
    except Exception:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    return entry_from_manifest(manifest, digest, final, root)


class PackageConflict(RuntimeError):
    """Same identity and version, different bytes."""


class PackageInvalid(contract.ContractError):
    """Package failed schema, hash, path or dependency checks."""


def read_manifest(pkg_dir: Path) -> tuple[dict[str, Any], str]:
    path = pkg_dir / "manifest.json"
    if not path.exists():
        raise PackageInvalid(f"manifest.json is missing in {pkg_dir}")
    raw = path.read_bytes()
    try:
        manifest = json.loads(raw.decode("utf-8"))
    except json.JSONDecodeError as exc:
        raise PackageInvalid(f"manifest.json is not valid JSON: {exc}") from exc
    return manifest, sha256_bytes(raw)


def validate_package(pkg_dir: Path, *, expected_asset: str | None = None,
                     check_files: bool = True) -> tuple[dict[str, Any], str]:
    manifest, digest = read_manifest(pkg_dir)
    try:
        contract.validate_manifest(manifest, pkg_dir=pkg_dir,
                                   check_files=check_files,
                                   expected_asset=expected_asset)
    except contract.ContractError as exc:
        raise PackageInvalid(str(exc)) from exc
    return manifest, digest


def package_capabilities(manifest: Mapping[str, Any], *, enabled: bool,
                         available: bool) -> list[str]:
    """Legacy list view used by the panel, agent tools and CLI output."""
    if not enabled or not available:
        return ["catalog"] + (["documentation_read"] if available else [])
    caps = manifest.get("capabilities")
    if isinstance(caps, Mapping):
        derived = [name for name, value in caps.items() if value]
    else:
        derived = [name for name in (caps or []) if name in CAPABILITIES]
    return sorted(set(derived) | {"catalog"})


def manifest_files(manifest: Mapping[str, Any]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for row in manifest.get("files") or []:
        out.setdefault(row["role"], []).append(row["path"])
    return out


def read_role(pkg_dir: Path, manifest: Mapping[str, Any], *roles: str) -> Any:
    """Read the first file registered under one of `roles`, parsed as JSON."""
    files = manifest_files(manifest)
    for role in roles:
        for rel in files.get(role, []):
            path = pkg_dir / rel
            if not path.exists():
                continue
            try:
                return json.loads(path.read_text(encoding="utf-8"))
            except json.JSONDecodeError:
                continue
    return None


def read_named(pkg_dir: Path, manifest: Mapping[str, Any], name: str) -> Any:
    """Read a listed file by its basename, whatever role it carries."""
    for row in manifest.get("files") or []:
        if row["path"].rsplit("/", 1)[-1] != name:
            continue
        path = pkg_dir / row["path"]
        if not path.exists():
            continue
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            return None
    return None


def read_text_role(pkg_dir: Path, manifest: Mapping[str, Any],
                   *roles: str) -> str | None:
    files = manifest_files(manifest)
    for role in roles:
        for rel in files.get(role, []):
            path = pkg_dir / rel
            if path.exists():
                return path.read_text(encoding="utf-8")
    return None


def iter_package_manifests(root: Path) -> Iterable[tuple[Path, dict[str, Any], str]]:
    for plural in PLURAL.values():
        base = root / plural
        if not base.exists():
            continue
        for manifest_path in base.glob("*/*/versions/*/manifest.json"):
            pkg_dir = manifest_path.parent
            try:
                manifest, digest = validate_package(pkg_dir, check_files=False)
            except (PackageInvalid, ValueError):
                continue
            yield pkg_dir, manifest, digest
